// ===== TYPES =====
export interface EventSession {
    title: string;
    learningOutcome: string;
    topic?: string;
    speaker?: string;
    time?: string;
}

export interface Trainer {
    name: string;
    role: string;
    image: string;
    isIITAlumni?: boolean;
}

export interface SubEvent {
    id: string;
    title: string;
    date?: string;
    duration?: string;
    summary: string;
    sessions: EventSession[];
    images: string[];
    learningObjectives?: string;
    premiumDetails?: PremiumDetails;
    trainers?: Trainer[];
}

export interface PremiumDetails {
    theme: string;
    heroImage?: string;
    relevance: string;
    objectives: string[];
    alignment: string[];
    pmUShAAlignment: string[];
    handson: {
        title: string;
        items: string[];
    }[];
    outcomes: string[];
    galleryGroups: {
        title: string;
        images: string[];
    }[];
    pressRelease?: {
        image?: string;
        images?: string[];
        text: string;
    };
    trainingModules?: {
        m: string | number;
        d: string;
        t: string;
        o: string;
        speaker?: string;
    }[];
}

export interface EventData {
    id: string;
    title: string;
    tag: 'Workshop' | 'Seminar' | 'Bootcamp' | 'Sessions' | 'Session' | 'Hackathon';
    tagline: string;
    shortDescription: string;
    date: string;
    venue: string;
    organizedBy: string;
    inAssociationWith?: string;
    cardImage: string;
    videoUrls?: string[];
    isActive: boolean;
    subEvents: SubEvent[];
    trainers?: Trainer[];
    premiumDetails?: PremiumDetails;
}

